import { Command } from 'commander';
import { sync } from '../../api/sync.js';
import { UsageError } from '../../core/errors.js';
import { ExitCode } from '../../core/exit-codes.js';
import type { Colors } from '../../core/logger.js';
import { AGENT_IDS, type AgentId } from '../../core/types.js';
import type { PlannedChange, SyncPlan } from '../../syncer/plan.js';
import { countActions, diffOf } from '../../syncer/write.js';
import { contextFor, globalOptions, loggerFor } from '../global-options.js';
import type { CommandRuntime } from '../io.js';
import { collect } from '../option-parsers.js';

interface SyncCliOptions {
  dryRun?: boolean;
  check?: boolean;
  target: string[];
  force?: boolean;
}

export function syncCommand(runtime: CommandRuntime): Command {
  return new Command('sync')
    .description('Compile .context/rules into each agent’s native instruction files')
    .option('--dry-run', 'print planned changes as diffs without writing')
    .option('--check', 'write nothing; exit 1 if generated files are out of date')
    .option(
      '--target <id>',
      `limit to one target: ${AGENT_IDS.join(', ')} (repeatable)`,
      collect,
      [],
    )
    .option('--force', 'take over files that were not generated by ctx-lint (overwrites them)')
    .action(async (options: SyncCliOptions, command: Command) => {
      const globals = globalOptions(command);
      const logger = loggerFor(globals, runtime);
      const c = logger.colors;
      const ctx = await contextFor(globals, logger);
      const targets = parseTargets(options.target);

      const result = await sync(ctx, {
        ...(targets ? { targets } : {}),
        force: options.force === true,
        dryRun: options.dryRun === true || options.check === true,
      });
      const { plan } = result;

      for (const warning of plan.warnings) logger.warn(warning);

      if (plan.problems.length > 0) {
        runtime.stderr(`${c.red('✖')} Invalid source rules; nothing was written:\n`);
        for (const p of plan.problems) runtime.stderr(`  ${p.file}: ${p.message}\n`);
        runtime.stderr(`Run \`ctx-lint check\` for details.\n`);
        runtime.exitCode = ExitCode.Failure;
        return;
      }
      if (plan.rules.length === 0) {
        throw new UsageError(
          `No source rules found in ${ctx.config.sources}. Run \`ctx-lint init\` to create one, or \`ctx-lint init --import\` to import your existing files.`,
        );
      }
      if (plan.conflicts.length > 0) {
        reportConflicts(runtime, plan, c);
        runtime.exitCode = ExitCode.Failure;
        return;
      }

      const pending = plan.changes.filter((ch) => ch.action !== 'unchanged');
      if (options.dryRun) {
        for (const change of pending) runtime.stdout(`${colorDiff(diffOf(change), c)}\n`);
      }
      for (const change of pending) runtime.stdout(`${describe(change, c)}\n`);

      const counts = countActions(plan.changes);
      if (options.check) {
        if (pending.length > 0) {
          runtime.stdout(
            `${c.red('✖')} ${pending.length} generated file${pending.length === 1 ? ' is' : 's are'} out of date. Run \`ctx-lint sync\` to update.\n`,
          );
          runtime.exitCode = ExitCode.Failure;
        } else {
          runtime.stdout(
            `${c.green('✔')} Generated files are up to date (${counts.unchanged} checked).\n`,
          );
        }
        return;
      }

      const summary = `${counts.create} created, ${counts.update} updated, ${counts.delete} deleted, ${counts.unchanged} unchanged`;
      runtime.stdout(
        options.dryRun
          ? `${c.dim('Dry run, nothing written:')} ${summary}\n`
          : `${c.green('✔')} ${summary} (${plan.rules.length} rule${plan.rules.length === 1 ? '' : 's'} → ${plan.targets.join(', ')})\n`,
      );
    });
}

function parseTargets(values: readonly string[]): AgentId[] | undefined {
  if (values.length === 0) return undefined;
  for (const value of values) {
    if (!(AGENT_IDS as readonly string[]).includes(value)) {
      throw new UsageError(`Unknown target "${value}". Targets: ${AGENT_IDS.join(', ')}.`);
    }
  }
  return values as AgentId[];
}

function reportConflicts(runtime: CommandRuntime, plan: SyncPlan, c: Colors): void {
  runtime.stderr(
    `${c.red('✖')} Nothing was written: ${plan.conflicts.length} file${plan.conflicts.length === 1 ? ' needs' : 's need'} attention.\n`,
  );
  for (const conflict of plan.conflicts) runtime.stderr(`  ${conflict.path}: ${conflict.reason}\n`);
  runtime.stderr(
    [
      '',
      'ctx-lint only replaces content it generated. For each file, either:',
      '  • run `ctx-lint init --import` to move its content into .context/rules, then `ctx-lint sync --force`;',
      '  • add `<!-- ctx-lint:begin -->` and `<!-- ctx-lint:end -->` lines where generated content should go; or',
      '  • re-run with `--force` to overwrite it (try `--dry-run --force` first).',
      '',
    ].join('\n'),
  );
}

const SYMBOL: Record<PlannedChange['action'], string> = {
  create: '+',
  update: '~',
  delete: '-',
  unchanged: '=',
};

function describe(change: PlannedChange, c: Colors): string {
  const color =
    change.action === 'create' ? c.green : change.action === 'delete' ? c.red : c.yellow;
  return `  ${color(`${SYMBOL[change.action]} ${change.action.padEnd(7)}`)} ${change.path}`;
}

function colorDiff(diff: string, c: Colors): string {
  return diff
    .split('\n')
    .map((line) => {
      if (line.startsWith('+++') || line.startsWith('---')) return c.bold(line);
      if (line.startsWith('+')) return c.green(line);
      if (line.startsWith('-')) return c.red(line);
      if (line.startsWith('@@')) return c.cyan(line);
      return line;
    })
    .join('\n');
}
