import { Command } from 'commander';
import { NotImplementedError } from '../../core/errors.js';
import { collect } from '../option-parsers.js';

export function syncCommand(): Command {
  return new Command('sync')
    .description('Compile .context/rules into each agent’s native instruction files')
    .option('--dry-run', 'print planned changes as diffs without writing')
    .option('--check', 'write nothing; exit 1 if generated files are out of date')
    .option('--target <id>', 'limit to one target (repeatable)', collect, [])
    .option('--force', 'overwrite files that were not generated by ctx-lint')
    .action(() => {
      throw new NotImplementedError('ctx-lint sync');
    });
}
