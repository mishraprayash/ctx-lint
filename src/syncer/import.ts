// `ctx-lint init --import`: existing agent files → source rules (PLAN.md §6.7).

export interface ImportedRule {
  /** Source rule id (file name without `.md`, may contain `/`). */
  id: string;
  description?: string;
  globs: string[];
  alwaysApply: boolean;
  body: string;
  /** Files this rule came from (several when identical content was merged). */
  from: string[];
  agents: AgentId[];
}

export interface ImportResult {
  rules: ImportedRule[];
  /** Files skipped, with why. */
  skipped: { path: string; reason: string }[];
  notes: string[];
}

const MONOLITHIC: Readonly<Record<string, { name: string; agent: AgentId }>> = {
  'CLAUDE.md': { name: 'imported-claude', agent: 'claude' },
  '.claude/CLAUDE.md': { name: 'imported-claude', agent: 'claude' },
  'AGENTS.md': { name: 'imported-agents', agent: 'agents' },
  '.github/copilot-instructions.md': { name: 'imported-copilot', agent: 'copilot' },
  '.cursorrules': { name: 'imported-cursorrules', agent: 'cursor' },
  '.windsurfrules': { name: 'imported-windsurfrules', agent: 'windsurf' },
};

export interface ImportOptions {
  split?: boolean;
  /** Bodies of source rules that already exist: content matching one isn't imported again. */
  existingBodies?: readonly string[];
}

const bodyKey = (body: string) => body.replace(/\s+/g, ' ').trim();

export function importFiles(
  files: readonly LoadedFile[],
  options: ImportOptions = {},
): ImportResult {
  const result: ImportResult = { rules: [], skipped: [], notes: [] };
  const byBody = new Map<string, ImportedRule>();
  const usedIds = new Set<string>();
  const alreadySourced = new Set((options.existingBodies ?? []).map(bodyKey));

  const add = (rule: Omit<ImportedRule, 'id'> & { id: string }): boolean => {
    const key = bodyKey(rule.body);
    if (alreadySourced.has(key)) {
      result.skipped.push({
        path: rule.from[0] as string,
        reason: 'content is already in a source rule',
      });
      return false;
    }
    const existing = byBody.get(key);
    if (existing) {
      // Identical content in several files (often CLAUDE.md and AGENTS.md): keep one rule.
      existing.from.push(...rule.from);
      for (const agent of rule.agents)
        if (!existing.agents.includes(agent)) existing.agents.push(agent);
      return true;
    }
    let id = rule.id;
    for (let n = 2; usedIds.has(id); n++) id = `${rule.id}-${n}`;
    usedIds.add(id);
    const created = { ...rule, id, from: [...rule.from], agents: [...rule.agents] };
    byBody.set(key, created);
    result.rules.push(created);
    return true;
  };

  // CLAUDE.md first, so content it shares with AGENTS.md is named after it.
  const ordered = [...files].sort(
    (a, b) => Number(b.path === 'CLAUDE.md') - Number(a.path === 'CLAUDE.md'),
  );
  for (const file of ordered) {
    if (file.kind !== 'instructions') continue;
    if (basenameRel(file.path) === 'CLAUDE.local.md') {
      result.skipped.push({
        path: file.path,
        reason: 'personal file (CLAUDE.local.md), not shared',
      });
      continue;
    }
    const region = findGenerated(file.content);
    if (region?.kind === 'file') {
      result.skipped.push({ path: file.path, reason: 'generated by ctx-lint' });
      continue;
    }
    // Keep only hand-written content: drop the frontmatter, then any managed block.
    const fm = file.markdown.frontmatter;
    let content = fm ? file.content.slice(fm.range.end.offset) : file.content;
    const block = findGenerated(content);
    if (block) content = content.slice(0, block.start) + content.slice(block.end);
    const body = content.trim();
    if (body === '') {
      result.skipped.push({ path: file.path, reason: 'no content' });
      continue;
    }
    if (body.split('\n').every((line) => /^@\S+\s*$/.test(line.trim()) || line.trim() === '')) {
      result.skipped.push({
        path: file.path,
        reason: 'only imports other files (e.g. `@AGENTS.md`)',
      });
      continue;
    }

    const data = fm?.data ?? {};
    const agent = file.agents[0] as AgentId;
    const from = [file.path];
    const ruleFile = perRuleFile(file.path);

    if (ruleFile) {
      const mapped = mapFrontmatter(ruleFile.format, data);
      if (mapped.manual) {
        result.notes.push(
          `${file.path} is a manual rule (only used when @-mentioned). It was imported as an optional rule; adjust its description.`,
        );
      }
      add({
        id: ruleFile.id,
        ...(mapped.description ? { description: mapped.description } : {}),
        globs: mapped.globs,
        alwaysApply: mapped.alwaysApply,
        body,
        from,
        agents: [agent],
      });
      continue;
    }

    const known = MONOLITHIC[file.path];
    if (known) {
      for (const part of options.split ? splitByH2(body, known.name) : [{ id: known.name, body }]) {
        add({
          id: part.id,
          ...(part.description ? { description: part.description } : {}),
          globs: [],
          alwaysApply: true,
          body: part.body,
          from,
          agents: [known.agent],
        });
      }
      continue;
    }

    // A nested CLAUDE.md / AGENTS.md applies to its directory.
    const dir = dirnameRel(file.path);
    const added = add({
      id: `imported-${dir.replaceAll('/', '-')}-${agent}`,
      description: `Rules for ${dir}`,
      globs: [`${dir}/**`],
      alwaysApply: false,
      body,
      from,
      agents: [agent],
    });
    if (added) {
      result.notes.push(
        `${file.path} was imported as a rule scoped to ${dir}/**. Delete it once you've checked the generated files, or agents will read both.`,
      );
    }
  }

  return result;
}

type RuleFormat = 'cursor' | 'claude' | 'copilot' | 'windsurf';

function perRuleFile(path: string): { format: RuleFormat; id: string } | null {
  let m = /^(?:.*\/)?\.cursor\/rules\/(.+)\.mdc$/.exec(path);
  if (m?.[1]) return { format: 'cursor', id: m[1] };
  m = /^\.claude\/rules\/(.+)\.md$/.exec(path);
  if (m?.[1]) return { format: 'claude', id: m[1] };
  m = /^\.github\/instructions\/(.+)\.instructions\.md$/.exec(path);
  if (m?.[1]) return { format: 'copilot', id: m[1] };
  m = /^(?:.*\/)?\.(?:windsurf|devin)\/rules\/(.+)\.md$/.exec(path);
  if (m?.[1]) return { format: 'windsurf', id: m[1] };
  return null;
}

interface MappedFrontmatter {
  description?: string;
  globs: string[];
  alwaysApply: boolean;
  manual: boolean;
}

/** Each format's frontmatter → source rule fields. */
function mapFrontmatter(format: RuleFormat, data: Record<string, unknown>): MappedFrontmatter {
  const text = (v: unknown) => (typeof v === 'string' && v.trim() !== '' ? v.trim() : undefined);
  const globsOf = (v: unknown): string[] =>
    typeof v === 'string'
      ? splitGlobList(v)
      : Array.isArray(v)
        ? v.filter((g): g is string => typeof g === 'string')
        : [];

  let description: string | undefined;
  let globs: string[] = [];
  let always = false;
  switch (format) {
    case 'cursor':
      description = text(data.description);
      globs = globsOf(data.globs);
      always = data.alwaysApply === true;
      break;
    case 'claude':
      globs = globsOf(data.paths);
      always = globs.length === 0;
      break;
    case 'copilot':
      description = text(data.description);
      globs = globsOf(data.applyTo);
      always = globs.length === 0 || (globs.length === 1 && globs[0] === '**');
      break;
    case 'windsurf':
      description = text(data.description);
      globs = data.trigger === 'glob' ? globsOf(data.globs) : [];
      always = data.trigger === 'always_on';
      break;
  }
  if (always)
    return { ...(description ? { description } : {}), globs: [], alwaysApply: true, manual: false };
  if (globs.length > 0)
    return { ...(description ? { description } : {}), globs, alwaysApply: false, manual: false };
  if (description) return { description, globs: [], alwaysApply: false, manual: false };
  return {
    description: 'Use when explicitly asked for (manual rule)',
    globs: [],
    alwaysApply: false,
    manual: true,
  };
}

/** `## Heading` sections → separate rules; text before the first H2 stays under `name`. */
function splitByH2(
  body: string,
  name: string,
): { id: string; body: string; description?: string }[] {
  const parts: { id: string; body: string; description?: string }[] = [];
  const lines = body.split('\n');
  let current: { title?: string; lines: string[] } = { lines: [] };
  let inFence = false;
  const flush = () => {
    const text = current.lines.join('\n').trim();
    if (text === '') return;
    if (current.title === undefined) parts.push({ id: name, body: text });
    else
      parts.push({ id: `${name}-${slug(current.title)}`, body: text, description: current.title });
  };
  for (const line of lines) {
    if (/^(```|~~~)/.test(line.trim())) inFence = !inFence;
    const h2 = inFence ? null : /^##\s+(.+?)\s*#*\s*$/.exec(line);
    if (h2?.[1]) {
      flush();
      current = { title: h2[1], lines: [line] };
    } else {
      current.lines.push(line);
    }
  }
  flush();
  return parts;
}

function slug(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 48) || 'section'
  );
}

/** The source rule file for an imported rule. */
export function renderImportedRule(rule: ImportedRule): string {
  const entries: [string, FrontmatterValue | undefined][] = [
    ['description', rule.description],
    ['globs', rule.globs.length > 0 ? rule.globs : undefined],
    ['alwaysApply', rule.alwaysApply],
  ];
  return `${renderFrontmatter(entries)}\n${rule.body.trim()}\n`;
}
