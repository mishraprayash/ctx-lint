import picomatch from 'picomatch';
import type { ProjectContext } from '../core/context.js';
import { normalizeRel } from '../core/paths.js';
import type { AgentId } from '../core/types.js';
import { TextCache } from '../fs/text-cache.js';
import type { OutputFile, TargetAdapter } from '../targets/adapter.js';
import { TARGETS } from '../targets/registry.js';
import { findGenerated, managedBlock, renderWholeFile, replaceBlock } from './generated.js';
import { loadSources, type RuleIR, type SourceProblem } from './ir.js';

// Compile → compare with disk → a plan of changes (PLAN.md §6.6). Nothing is written here.

export type SyncAction = 'create' | 'update' | 'unchanged' | 'delete';

export interface PlannedChange {
  path: string;
  target: AgentId;
  action: SyncAction;
  /** Current content (`null` when the file doesn't exist). */
  before: string | null;
  /** Content after sync (`null` when the file is deleted). */
  after: string | null;
}

export interface SyncConflict {
  path: string;
  reason: string;
}

export interface SyncPlan {
  rules: RuleIR[];
  targets: AgentId[];
  changes: PlannedChange[];
  conflicts: SyncConflict[];
  problems: SourceProblem[];
  warnings: string[];
}

export interface PlanOptions {
  /** Only these targets (default: the enabled ones). */
  targets?: readonly AgentId[];
  /** Take over files that weren't generated by ctx-lint. */
  force?: boolean;
}

export async function planSync(ctx: ProjectContext, options: PlanOptions = {}): Promise<SyncPlan> {
  const { config } = ctx;
  const { rules, problems } = await loadSources(ctx);
  const selected = TARGETS.filter((t) =>
    options.targets ? options.targets.includes(t.id) : config.targets[t.id].enabled,
  );
  const plan: SyncPlan = {
    rules,
    targets: selected.map((t) => t.id),
    changes: [],
    conflicts: [],
    problems,
    warnings: [],
  };
  if (problems.length > 0) return plan;

  const text = new TextCache(ctx.root);
  const sources = normalizeRel(config.sources);
  const produced = new Map<string, AgentId>();

  for (const target of selected) {
    const outputs = target.compile(
      rules.filter((rule) => rule.targets.includes(target.id)),
      { config },
    );
    for (const output of outputs) {
      const owner = produced.get(output.path);
      if (owner !== undefined) {
        plan.conflicts.push({
          path: output.path,
          reason: `both ${owner} and ${target.id} write this file`,
        });
        continue;
      }
      produced.set(output.path, target.id);
      plan.warnings.push(...(output.warnings ?? []));
      const change = planOutput(
        output,
        text.read(output.path),
        sources,
        config.mode,
        options.force === true,
      );
      if ('reason' in change) plan.conflicts.push(change);
      else if (change.action !== 'unchanged' || change.before !== null) plan.changes.push(change);
    }
    plan.changes.push(...orphans(ctx, target, produced, text));
  }

  plan.changes.sort((a, b) => a.path.localeCompare(b.path));
  return plan;
}

function planOutput(
  output: OutputFile,
  existing: string | null,
  sources: string,
  mode: 'managed-block' | 'file',
  force: boolean,
): PlannedChange | SyncConflict {
  const base = { path: output.path, target: output.target, before: existing };
  const region = existing === null ? null : findGenerated(existing);
  const empty = output.body.trim() === '';

  // Files ctx-lint owns entirely: per-rule files, `mode: "file"`, or a file that was generated whole.
  if (output.perRule || mode === 'file' || region?.kind === 'file') {
    const desired = empty ? null : renderWholeFile(sources, output.body, output.frontmatter);
    if (existing === null)
      return { ...base, action: desired === null ? 'unchanged' : 'create', after: desired };
    if (region?.kind !== 'file' && !force) {
      if (desired === null) return { ...base, action: 'unchanged', after: existing };
      return { path: output.path, reason: 'exists and was not generated by ctx-lint' };
    }
    if (desired === null) return { ...base, action: 'delete', after: null };
    return { ...base, action: existing === desired ? 'unchanged' : 'update', after: desired };
  }

  // Managed block: only the content between the markers is ours.
  if (empty) {
    if (region?.kind !== 'block' || existing === null)
      return { ...base, action: 'unchanged', after: existing };
    const rest = (existing.slice(0, region.start) + existing.slice(region.end)).trim();
    return rest === ''
      ? { ...base, action: 'delete', after: null }
      : { ...base, action: 'update', after: `${rest}\n` };
  }
  const block = managedBlock(sources, output.body);
  if (existing === null) return { ...base, action: 'create', after: `${block}\n` };
  if (region?.kind === 'block') {
    const after = replaceBlock(existing, block);
    return { ...base, action: after === existing ? 'unchanged' : 'update', after };
  }
  if (!force) return { path: output.path, reason: 'exists and has no ctx-lint markers' };
  return { ...base, action: 'update', after: `${block}\n` };
}

/** Generated files of this target that no rule produces any more. Hand-written files are never touched. */
function orphans(
  ctx: ProjectContext,
  target: TargetAdapter,
  produced: ReadonlyMap<string, AgentId>,
  text: TextCache,
): PlannedChange[] {
  const owned = target.ownedDirs(ctx.config).map((dir) => `${normalizeRel(dir)}/**`);
  const isCandidate = picomatch([...target.detect, ...owned], { dot: true });
  const changes: PlannedChange[] = [];
  for (const path of ctx.files.files()) {
    if (produced.has(path) || !isCandidate(path)) continue;
    const content = text.read(path);
    const region = content === null ? null : findGenerated(content);
    if (!region || content === null) continue;
    if (region.kind === 'file') {
      changes.push({ path, target: target.id, action: 'delete', before: content, after: null });
    } else {
      const rest = (content.slice(0, region.start) + content.slice(region.end)).trim();
      changes.push({
        path,
        target: target.id,
        action: rest === '' ? 'delete' : 'update',
        before: content,
        after: rest === '' ? null : `${rest}\n`,
      });
    }
  }
  return changes;
}
