import { LineMap } from '../../core/line-map.js';
import { findGenerated } from '../../syncer/generated.js';
import type { LintRule } from '../rule.js';

export const generatedFileModified: LintRule = {
  id: 'generated-file-modified',
  meta: {
    description: 'Content generated by `ctx-lint sync` has not been edited by hand.',
    defaultSeverity: 'warn',
  },
  file(file, ctx) {
    const region = findGenerated(file.content);
    // Hand-added markers have no hash yet; there's nothing to compare against.
    if (!region || region.recordedHash === null || region.recordedHash === region.actualHash)
      return;
    const lines = new LineMap(file.content);
    const where = region.kind === 'file' ? 'This file was' : 'The generated block in this file was';
    ctx.report({
      message: `${where} edited by hand since \`ctx-lint sync\` generated it; the edits will be lost on the next sync. Change the source rules in ${ctx.project.config.sources} instead.`,
      range: { start: lines.position(region.markerStart), end: lines.position(region.markerEnd) },
    });
  },
};
