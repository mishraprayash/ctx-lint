import { describe, expect, it } from 'vitest';
import {
  findGenerated,
  hashBody,
  managedBlock,
  renderWholeFile,
  replaceBlock,
} from '../../../src/syncer/generated.js';
import { renderFrontmatter, yamlScalar } from '../../../src/syncer/yaml.js';

describe('generated content', () => {
  it('hashes bodies independent of line endings and surrounding whitespace', () => {
    expect(hashBody('a\r\nb\n\n')).toBe(hashBody('\na\nb'));
    expect(hashBody('a')).not.toBe(hashBody('b'));
  });

  it('round-trips a whole file, with the header after the frontmatter', () => {
    const file = renderWholeFile('.context/rules', '- hi', '---\nalwaysApply: true\n---\n');
    expect(file.startsWith('---\nalwaysApply: true\n---\n<!-- Generated by ctx-lint')).toBe(true);
    const region = findGenerated(file);
    expect(region).toMatchObject({ kind: 'file', start: 0, end: file.length });
    expect(region?.recordedHash).toBe(region?.actualHash);
  });

  it('detects hand edits', () => {
    const file = renderWholeFile('.context/rules', '- hi');
    const region = findGenerated(`${file}- edited\n`);
    expect(region?.recordedHash).not.toBe(region?.actualHash);
  });

  it('only treats a header at the top as a whole-file header', () => {
    const header = renderWholeFile('.context/rules', 'x').split('\n')[0];
    expect(findGenerated(`# Mine\n\n${header}\n`)).toBeNull();
  });

  it('replaces a managed block and keeps everything around it', () => {
    const before = `# My notes\n\n${managedBlock('.context/rules', 'old')}\n\nMore notes.\n`;
    const after = replaceBlock(before, managedBlock('.context/rules', 'new'));
    expect(after).toContain('# My notes');
    expect(after).toContain('More notes.');
    expect(after).toContain('\nnew\n');
    expect(after).not.toContain('\nold\n');
    expect(findGenerated(after)?.kind).toBe('block');
  });

  it('accepts hand-added markers without a hash', () => {
    const region = findGenerated('# Mine\n\n<!-- ctx-lint:begin -->\n<!-- ctx-lint:end -->\n');
    expect(region).toMatchObject({ kind: 'block', recordedHash: null });
  });
});

describe('frontmatter writer', () => {
  it.each([
    ['src/api/**/*.ts', 'src/api/**/*.ts'],
    ['**/*.ts', '"**/*.ts"'],
    ['API routes: v2', '"API routes: v2"'],
    ['true', '"true"'],
    ['42', '"42"'],
    ['# heading', '"# heading"'],
    ['Use zod', 'Use zod'],
  ])('%j → %s', (input, expected) => {
    expect(yamlScalar(input)).toBe(expected);
  });

  it('writes keys in order, null as empty, lists quoted, and forced quotes', () => {
    expect(
      renderFrontmatter(
        [
          ['description', null],
          ['paths', ['src/**', '*.md']],
          ['applyTo', 'a,b'],
          ['alwaysApply', false],
          ['skipped', undefined],
        ],
        { quote: new Set(['applyTo']) },
      ),
    ).toBe(
      '---\ndescription:\npaths:\n  - "src/**"\n  - "*.md"\napplyTo: "a,b"\nalwaysApply: false\n---\n',
    );
  });
});

describe('shiftHeadings', () => {
  it('nests body headings under the section and leaves code fences alone', async () => {
    const { shiftHeadings } = await import('../../../src/targets/compose.js');
    expect(shiftHeadings('# Top\n\n## Sub\n\n```md\n# not a heading\n```', 3)).toBe(
      '### Top\n\n#### Sub\n\n```md\n# not a heading\n```',
    );
    expect(shiftHeadings('no headings', 2)).toBe('no headings');
  });
});
